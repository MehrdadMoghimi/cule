def compute_baseline_loss(advantages, reduction="sum"):
    """0.5 * ||vs - V||^2. torchbeast sums; `mean` is offered for comparability."""
    squared = advantages**2
    return 0.5 * (squared.sum() if reduction == "sum" else squared.mean())


def compute_entropy_loss(logits, reduction="sum"):
    """*Negative* entropy — a loss, so minimising it maximises entropy."""
    policy = F.softmax(logits, dim=-1)
    log_policy = F.log_softmax(logits, dim=-1)
    per_step = (policy * log_policy).sum(dim=-1)
    return per_step.sum() if reduction == "sum" else per_step.mean()


def compute_policy_gradient_loss(logits, actions, advantages, reduction="sum"):
    """`sum(-log pi(a|x) * A)`, with the advantage treated as data."""
    cross_entropy = F.nll_loss(
        F.log_softmax(torch.flatten(logits, 0, -2), dim=-1),
        target=torch.flatten(actions),
        reduction="none",
    ).view_as(advantages)
    weighted = cross_entropy * advantages.detach()
    return weighted.sum() if reduction == "sum" else weighted.mean()


def layer_init(layer, std=np.sqrt(2), bias_const=0.0):
    torch.nn.init.orthogonal_(layer.weight, std)
    torch.nn.init.constant_(layer.bias, bias_const)
    return layer


# The residual encoder from the IMPALA paper's "deep" model, in the widths the
# paper uses. Same module as `qdagger_dqn_atari_impalacnn.py` carries.
class ResidualBlock(nn.Module):
    def __init__(self, channels):
        super().__init__()
        self.conv0 = nn.Conv2d(channels, channels, 3, padding=1)
        self.conv1 = nn.Conv2d(channels, channels, 3, padding=1)

    def forward(self, x):
        inputs = x
        x = F.relu(x)
        x = self.conv0(x)
        x = F.relu(x)
        x = self.conv1(x)
        return x + inputs


class ConvSequence(nn.Module):
    def __init__(self, input_shape, out_channels):
        super().__init__()
        self._input_shape = input_shape
        self._out_channels = out_channels
        self.conv = nn.Conv2d(input_shape[0], out_channels, 3, padding=1)
        self.res_block0 = ResidualBlock(out_channels)
        self.res_block1 = ResidualBlock(out_channels)

    def forward(self, x):
        x = self.conv(x)
        x = F.max_pool2d(x, kernel_size=3, stride=2, padding=1)
        x = self.res_block0(x)
        return self.res_block1(x)

    def get_output_shape(self):
        _c, h, w = self._input_shape
        return (self._out_channels, (h + 1) // 2, (w + 1) // 2)


class Agent(nn.Module):
    """Shared torso, a policy-logit head and a scalar baseline head."""

    def __init__(self, envs, encoder="nature"):
        super().__init__()
        self.encoder = encoder
        if encoder == "nature":
            self.network = nn.Sequential(
                layer_init(nn.Conv2d(4, 32, 8, stride=4)),
                nn.ReLU(),
                layer_init(nn.Conv2d(32, 64, 4, stride=2)),
                nn.ReLU(),
                layer_init(nn.Conv2d(64, 64, 3, stride=1)),
                nn.ReLU(),
                nn.Flatten(),
                layer_init(nn.Linear(64 * 7 * 7, 512)),
                nn.ReLU(),
            )
        elif encoder == "impala":
            shape = envs.single_observation_space.shape
            layers = []
            for out_channels in (16, 32, 32):
                sequence = ConvSequence(shape, out_channels)
                shape = sequence.get_output_shape()
                layers.append(sequence)
            layers += [nn.ReLU(), nn.Flatten(), layer_init(nn.Linear(int(np.prod(shape)), 512)), nn.ReLU()]
            self.network = nn.Sequential(*layers)
        else:
            raise ValueError(f"unsupported encoder: {encoder}")
        self.actor = layer_init(nn.Linear(512, envs.single_action_space.n), std=0.01)
        self.critic = layer_init(nn.Linear(512, 1), std=1)

    def forward(self, x):
        hidden = self.network(x / 255.0)
        return self.actor(hidden), self.critic(hidden).squeeze(-1)

    def get_value(self, x):
        return self.forward(x)[1]

    def get_action_logits_and_value(self, x):
        logits, value = self.forward(x)
        return Categorical(logits=logits).sample(), logits, value


def build_optimizer(parameters, args):
    """torchbeast's optimiser: RMSProp at eps=1e-2, which is unusually large."""
    return optim.RMSprop(
        parameters,
        lr=args.learning_rate,
        momentum=args.rmsprop_momentum,
        eps=args.rmsprop_eps,
        alpha=args.rmsprop_alpha,
    )


def torchbeast_lr_fraction(consumed_steps, total_timesteps):
    """torchbeast's `lr_lambda`: `1 - min(epoch * T * B, total) / total`."""
    return 1.0 - min(consumed_steps, total_timesteps) / total_timesteps


