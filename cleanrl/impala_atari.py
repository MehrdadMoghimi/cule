# IMPALA with V-trace for Atari.
#
# Espeholt et al., ICML 2018, "IMPALA: Scalable Distributed Deep-RL with
# Importance Weighted Actor-Learner Architectures" (https://arxiv.org/abs/1802.01561).
#
# IMPALA makes two contributions and they are separable:
#
#   1. a *systems* contribution — hundreds of actors generating trajectories
#      asynchronously against a single learner, which is what buys the 250k
#      frames/s the paper reports; and
#   2. an *algorithmic* contribution — V-trace, the off-policy correction that
#      makes (1) sound. Actors always hold stale weights, so the trajectories
#      arriving at the learner were generated by a policy mu that is not the
#      learner's current pi. V-trace reweights them with truncated importance
#      ratios and stays a contraction.
#
# This file is (2), on this repository's synchronous vectorised rollout. The
# V-trace transcription is from facebookresearch/torchbeast
# (https://github.com/facebookresearch/torchbeast, `torchbeast/core/vtrace.py`,
# Apache 2.0), which is itself a direct PyTorch port of DeepMind's original
# `scalable_agent/vtrace.py`; the learner losses follow `monobeast.py`.
#
# A synchronous learner has no natural staleness, so at the defaults
# (`--actor-lag 0 --update-epochs 1 --num-minibatches 1`) the behaviour policy
# *is* the target policy, every rho is exactly 1, and V-trace collapses to
# ordinary n-step returns. That is not a bug and it is not a straw man: it is
# what IMPALA reduces to when the asynchrony is removed, and
# `tests/test_impala_equivalence.py` pins the reduction. Three knobs put the
# off-policyness back:
#
#   --actor-lag K       act with learner weights from K updates ago, which is
#                       what an asynchronous actor pool produces;
#   --update-epochs E   reuse each rollout E times, so passes 2..E are off-policy;
#   --num-minibatches M split the rollout, so minibatches 2..M are off-policy.
#
# The last two are how PPO creates off-policy data too — the difference is that
# PPO handles it with a clipping heuristic while V-trace handles it with a
# correction that has a fixed point.
#
# Two details worth stating because they are easy to get wrong:
#
#   * torchbeast's losses are `torch.sum`, not `torch.mean`. With unroll 80 and
#     batch 32 that is a factor of 2560 folded into the learning rate. This port
#     keeps `sum` (`--loss-reduction sum`, the default) so torchbeast's
#     `learning_rate=0.00048` and `grad_norm_clipping=40` mean what they mean.
#   * `discounts = (1 - done) * gamma`, and the done that belongs to step t is
#     the one *produced by* step t.
