def make_env(env_id, seed, idx, capture_video, run_name):
    def thunk():
        if capture_video and idx == 0:
            env = gym.make(env_id, render_mode="rgb_array")
            env = gym.wrappers.RecordVideo(env, f"videos/{run_name}")
        else:
            env = gym.make(env_id)
        env = gym.wrappers.RecordEpisodeStatistics(env)
        env = NoopResetEnv(env, noop_max=30)
        env = MaxAndSkipEnv(env, skip=4)
        env = EpisodicLifeEnv(env)
        if "FIRE" in env.unwrapped.get_action_meanings():
            env = FireResetEnv(env)
        env = ClipRewardEnv(env)
        env = gym.wrappers.ResizeObservation(env, (84, 84))
        env = grayscale_observation(env)
        env = frame_stack_observation(env, 4)
        env.action_space.seed(seed)
        return env

    return thunk


class RecordEpisodeStatistics(gym.Wrapper):
    """Expose EnvPool spaces and full-game statistics to the trainer."""

    def __init__(self, env):
        super().__init__(env)
        self.num_envs = getattr(env, "num_envs", 1)
        self.single_action_space = getattr(env, "single_action_space", env.action_space)
        self.single_observation_space = getattr(env, "single_observation_space", env.observation_space)

    def reset(self, **kwargs):
        observations = super().reset(**kwargs)
        self.episode_returns = np.zeros(self.num_envs, dtype=np.float32)
        self.episode_lengths = np.zeros(self.num_envs, dtype=np.int32)
        self.returned_episode_returns = np.zeros(self.num_envs, dtype=np.float32)
        self.returned_episode_lengths = np.zeros(self.num_envs, dtype=np.int32)
        return observations

    def step(self, action):
        result = super().step(action)
        if len(result) == 5:
            observations, rewards, terminations, truncations, infos = result
            dones = np.logical_or(terminations, truncations)
        else:
            observations, rewards, dones, infos = result
        self.episode_returns += infos["reward"]
        self.episode_lengths += 1
        self.returned_episode_returns[:] = self.episode_returns
        self.returned_episode_lengths[:] = self.episode_lengths
        game_over = np.logical_and(dones, np.asarray(infos["lives"]) == 0)
        self.episode_returns *= 1 - game_over
        self.episode_lengths *= 1 - game_over
        infos["r"] = self.returned_episode_returns
        infos["l"] = self.returned_episode_lengths
        if len(result) == 5:
            return observations, rewards, terminations, truncations, infos
        return observations, rewards, dones, infos


def completed_episode_infos(infos, dones):
    """Normalize per-backend episode statistics to the `final_info` format."""
    if "final_info" in infos:
        return infos
    if "r" in infos:  # EnvPool RecordEpisodeStatistics
        game_over = to_numpy(dones).astype(bool) & (np.asarray(infos["lives"]) == 0)
        if game_over.any():
            return {
                "final_info": [
                    {"episode": {"r": float(infos["r"][index]), "l": int(infos["l"][index])}}
                    for index in np.flatnonzero(game_over)
                ]
            }
    return {}


# ---------------------------------------------------------------------------
# V-trace
#
# Transcribed from torchbeast's `core/vtrace.py`, which is DeepMind's
# `scalable_agent/vtrace.py` ported to PyTorch. Kept as free functions on
# [T, B] tensors so the tests can drive them directly.
# ---------------------------------------------------------------------------

def action_log_probs(policy_logits, actions):
    """log pi(a_t | x_t) for the taken actions, on [T, B, A] logits."""
    return -F.nll_loss(
        F.log_softmax(torch.flatten(policy_logits, 0, -2), dim=-1),
        torch.flatten(actions),
        reduction="none",
    ).view_as(actions)


@torch.no_grad()
def vtrace_from_importance_weights(
    log_rhos,
    discounts,
    rewards,
    values,
    bootstrap_value,
    clip_rho_threshold=1.0,
    clip_pg_rho_threshold=1.0,
):
    """V-trace targets `vs` and policy-gradient advantages, from log(pi/mu).

    Equation 1 of the IMPALA paper:

        v_s = V(x_s) + sum_t gamma^(t-s) (prod_{i=s}^{t-1} c_i) delta_t V

    with `delta_t V = rho_t (r_t + gamma V(x_{t+1}) - V(x_t))`,
    `rho_t = min(rho_bar, pi/mu)` and `c_i = min(1, pi/mu)`. Written as the
    backward recursion

        vs_minus_v_xs[t] = delta_t V + gamma * c_t * vs_minus_v_xs[t+1]

    which is the form the reference implements.

    `rho_bar` bounds the bias of the fixed point (which policy V-trace converges
    to); `c_bar` — hard-coded to 1 here as in every reference — bounds the
    variance of the product of traces.
    """
    rhos = torch.exp(log_rhos)
    clipped_rhos = rhos if clip_rho_threshold is None else torch.clamp(rhos, max=clip_rho_threshold)
    cs = torch.clamp(rhos, max=1.0)

    values_t_plus_1 = torch.cat([values[1:], bootstrap_value.unsqueeze(0)], dim=0)
    deltas = clipped_rhos * (rewards + discounts * values_t_plus_1 - values)

    acc = torch.zeros_like(bootstrap_value)
    result = []
    for t in range(discounts.shape[0] - 1, -1, -1):
        acc = deltas[t] + discounts[t] * cs[t] * acc
        result.append(acc)
    result.reverse()
    vs = torch.stack(result) + values

    # The policy-gradient advantage bootstraps off `vs`, not off `values`.
    broadcasted_bootstrap = torch.ones_like(vs[0]) * bootstrap_value
    vs_t_plus_1 = torch.cat([vs[1:], broadcasted_bootstrap.unsqueeze(0)], dim=0)
    clipped_pg_rhos = rhos if clip_pg_rho_threshold is None else torch.clamp(rhos, max=clip_pg_rho_threshold)
    pg_advantages = clipped_pg_rhos * (rewards + discounts * vs_t_plus_1 - values)
    return vs, pg_advantages


def vtrace_from_logits(
    behavior_policy_logits,
    target_policy_logits,
    actions,
    discounts,
    rewards,
    values,
    bootstrap_value,
    clip_rho_threshold=1.0,
    clip_pg_rho_threshold=1.0,
):
    """V-trace for softmax policies; returns `(vs, pg_advantages, log_rhos)`."""
    target_log_probs = action_log_probs(target_policy_logits, actions)
    behavior_log_probs = action_log_probs(behavior_policy_logits, actions)
    log_rhos = target_log_probs - behavior_log_probs
    vs, pg_advantages = vtrace_from_importance_weights(
        log_rhos=log_rhos,
        discounts=discounts,
        rewards=rewards,
        values=values,
        bootstrap_value=bootstrap_value,
        clip_rho_threshold=clip_rho_threshold,
        clip_pg_rho_threshold=clip_pg_rho_threshold,
    )
    return vs, pg_advantages, log_rhos


