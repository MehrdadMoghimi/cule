# DPO (Discovered Policy Optimisation) for Atari.
#
# Lu, Kuba, Letcher, Metz, de Witt and Foerster, NeurIPS 2022,
# "Discovered Policy Optimisation" (https://arxiv.org/abs/2210.05639).
# Ported from the authors' reference in luchris429/purejaxrl
# (`purejaxrl/dpo_continuous_action.py`, MIT).
#
# Mirror Learning says a policy-optimisation algorithm is sound if its objective
# is `ratio * A - drift(ratio, A)` for a *drift* that is non-negative and zero
# with zero gradient at `ratio = 1`. PPO's clip is one crude member of that
# family. The paper meta-learned over the whole space (giving LPO), inspected
# what the learned drift was doing, and distilled it into a closed form:
#
#     A >= 0:  drift = relu( (ratio - 1) A - alpha tanh( (ratio - 1) A / alpha ) )
#     A <  0:  drift = relu( log(ratio) A - beta  tanh( log(ratio) A / beta  ) )
#
# with alpha = 2.0, beta = 0.6. Two things separate it from clipping. It is
# **smooth**: the penalty grows continuously instead of switching off, so a
# minibatch that has drifted far still produces a gradient rather than a flat
# zero. And it is **asymmetric**: the negative-advantage branch measures
# distance in `log(ratio)` rather than `ratio`.
#
# Each branch is also *one-sided*, which is easy to miss from the formula.
# `relu(u - c tanh(u/c))` is identically zero for `u <= 0`, so the positive
# branch fires only when `ratio > 1` and the negative branch only when
# `ratio < 1`. In words: DPO penalises raising the probability of a good action
# too far, penalises *lowering* the probability of a bad action too far, and is
# silent in the other two quadrants. That second penalty is the "rollback"
# optimism the paper identifies — an action that scored badly is held back from
# being abandoned rather than driven towards zero probability.
#
# That is the whole diff from `ppo_atari.py`. `dpo_policy_loss` replaces the
# clipped surrogate; GAE, the value loss, minibatching, Adam and the annealing
# are untouched, and `--clip-coef` survives only because the *value* loss still
# clips.
